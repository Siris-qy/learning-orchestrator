def _validate(conn):
    problems = []
    ids = [q['id'] for q in QUESTIONS]
    if len(ids) != len(set(ids)):
        problems.append('duplicate ids in QUESTIONS')
    bad_groups = sorted({q['group_key'] for q in QUESTIONS}
                        - set(_GROUPS))
    if bad_groups:
        problems.append('unknown group_key: %s' % bad_groups)
    known_points = {r[0] for r in conn.execute(
        'SELECT point_id FROM review_items WHERE course_id=?', (COURSE_ID,))}
    if known_points:
        for q in QUESTIONS:
            missing = sorted(set(q['points']) - known_points)
            if missing:
                problems.append('%s: unknown point_id %s' % (q['id'], missing))
    empty_lines = [q['id'] for q in QUESTIONS if not q['source_lines']]
    if empty_lines:
        problems.append('questions without source lines: %s' % empty_lines)
    return problems


def migrate(conn):
    """Import the split question bank and mark the 24 material-pool sections
    migrated. Idempotent (import_questions upserts by id; pool rows upsert by
    (source_id, section)). Validates first and raises on any problem, so a
    bad seed never reaches the database."""
    from .graph import ValidationError
    problems = _validate(conn)
    if problems:
        raise ValidationError('question seed validation failed: '
                              + '; '.join(problems))
    report = questions.import_questions(
        conn, [dict(q, course_id=COURSE_ID) for q in QUESTIONS], ORIGIN)
    by_group = {}
    for q in QUESTIONS:
        by_group.setdefault(q['group_key'], []).append(q['id'])
    for group in _GROUPS:
        questions.set_pool_status(
            conn, POOL_SOURCE, group, 'migrated', by_group.get(group, []),
            note='2026-09-24 迁入结构化题库；原文归档于 '
                 '正式笔记/archive/2026-09-24-08-interview-question-index.md')
    report['groups'] = {g: len(ids) for g, ids in by_group.items()}
    report['pool_rows'] = len(_GROUPS)
    return report
